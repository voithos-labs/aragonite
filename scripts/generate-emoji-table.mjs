// Regenerates `src/lib/plugins/emoji/emoji-table.ts` from github/gemoji's canonical
// `db/emoji.json`. Run explicitly by a developer; the plugin ships the table checked in
// and pulls no data at build or runtime. `--input <file>` regenerates from a local copy.
// The output is deterministic (aliases sorted) and `.prettierignore`d — the emitted form
// is the committed form, and `scripts/verify-emoji-table.mjs` gates that equality.
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

// Pinned to a commit, not `master`: a moving ref makes a regen unreproducible and lets an
// upstream glyph or alias change arrive unreviewed. Bump, regenerate, and review together.
export const GEMOJI_DB_URL =
	'https://raw.githubusercontent.com/github/gemoji/0eca75db9301421efc8710baf7a7576793ae452a/db/emoji.json';
export const EMOJI_TABLE_PATH = 'src/lib/plugins/emoji/emoji-table.ts';

// ── Pure core (unit-tested) ───────────────────────────────────────────────────

/**
 * One pair per alias, sorted by shortcode so the output is independent of upstream
 * ordering. An entry missing a glyph or aliases is skipped, not emitted as a broken key.
 * @param {Array<{ emoji?: string; aliases?: string[] }>} db
 * @returns {Array<[string, string]>}
 */
export function emojiTableEntries(db) {
	/** @type {Array<[string, string]>} */
	const entries = [];
	for (const entry of db) {
		if (typeof entry.emoji !== 'string' || !Array.isArray(entry.aliases)) continue;
		for (const alias of entry.aliases) entries.push([alias, entry.emoji]);
	}
	entries.sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
	return entries;
}

/**
 * @param {Array<[string, string]>} entries
 * @returns {string}
 */
export function renderEmojiTable(entries) {
	const rows = entries.map(
		([alias, glyph]) => `\t[${JSON.stringify(alias)}, ${JSON.stringify(glyph)}]`
	);
	return (
		`// GENERATED by scripts/generate-emoji-table.mjs — do not edit by hand.\n` +
		`// Source: github/gemoji db/emoji.json (each shortcode alias mapped to its glyph).\n` +
		`// Regenerate: node scripts/generate-emoji-table.mjs\n\n` +
		`export const EMOJI_TABLE: ReadonlyMap<string, string> = new Map([\n` +
		`${rows.join(',\n')}\n` +
		`]);\n`
	);
}

// ── Source loading (shared with verify-emoji-table.mjs) ───────────────────────

/**
 * The gemoji db, from a local path when given and the pinned revision otherwise.
 * @param {string | undefined} input
 */
export async function loadGemojiDb(input) {
	if (input) return JSON.parse(await readFile(input, 'utf8'));
	const res = await fetch(GEMOJI_DB_URL);
	if (!res.ok) throw new Error(`gemoji fetch failed: ${res.status} ${res.statusText}`);
	return res.json();
}

// ── CLI ────────────────────────────────────────────────────────────────────────

/** @param {string[]} argv */
function parseArgs(argv) {
	let input;
	let output = EMOJI_TABLE_PATH;
	for (let i = 0; i < argv.length; i++) {
		if (argv[i] === '--input') input = argv[++i];
		else if (argv[i] === '--output') output = argv[++i];
	}
	return { input, output };
}

async function main() {
	const { input, output } = parseArgs(process.argv.slice(2));
	const db = await loadGemojiDb(input);
	const entries = emojiTableEntries(db);
	await writeFile(path.resolve(output), renderEmojiTable(entries), 'utf8');
	console.log(`wrote ${entries.length} shortcodes to ${output}`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
	main().catch((err) => {
		console.error(err);
		process.exit(1);
	});
}

// Regenerates `src/lib/plugins/emoji/emoji-table.ts` from github/gemoji's canonical
// `db/emoji.json`. Run explicitly by a developer — the emoji plugin ships the
// generated table checked in and pulls no data at build or runtime.
//
//   node scripts/generate-emoji-table.mjs                 # fetch the live gemoji db
//   node scripts/generate-emoji-table.mjs --input db.json # regenerate from a local copy
//
// The output is deterministic (aliases sorted), so a regen against the same input
// reproduces the file byte-for-byte. The table is `.prettierignore`d — the emitted
// form is the committed form.
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const GEMOJI_DB_URL = 'https://raw.githubusercontent.com/github/gemoji/master/db/emoji.json';
const DEFAULT_OUTPUT = 'src/lib/plugins/emoji/emoji-table.ts';

// ── Pure core (unit-tested) ───────────────────────────────────────────────────

/**
 * Flatten gemoji entries to `[shortcode, glyph]` pairs — one per alias — sorted by
 * shortcode so the output is independent of upstream ordering. An entry missing a
 * glyph or aliases is skipped rather than emitting a broken key.
 * @param {Array<{ emoji?: string; aliases?: string[] }>} db
 * @returns {Array<[string, string]>}
 */
export function emojiTableEntries(db) {
	/** @type {Array<[string, string]>} */
	const entries = [];
	for (const entry of db) {
		if (typeof entry.emoji !== 'string' || !Array.isArray(entry.aliases)) continue;
		for (const alias of entry.aliases) entries.push([alias, entry.emoji]);
	}
	entries.sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
	return entries;
}

/**
 * Render the checked-in `emoji-table.ts` source for a set of entries.
 * @param {Array<[string, string]>} entries
 * @returns {string}
 */
export function renderEmojiTable(entries) {
	const rows = entries.map(
		([alias, glyph]) => `\t[${JSON.stringify(alias)}, ${JSON.stringify(glyph)}]`
	);
	return (
		`// GENERATED by scripts/generate-emoji-table.mjs — do not edit by hand.\n` +
		`// Source: github/gemoji db/emoji.json (each shortcode alias mapped to its glyph).\n` +
		`// Regenerate: node scripts/generate-emoji-table.mjs\n\n` +
		`export const EMOJI_TABLE: ReadonlyMap<string, string> = new Map([\n` +
		`${rows.join(',\n')}\n` +
		`]);\n`
	);
}

// ── CLI ────────────────────────────────────────────────────────────────────────

/** @param {string[]} argv */
function parseArgs(argv) {
	let input;
	let output = DEFAULT_OUTPUT;
	for (let i = 0; i < argv.length; i++) {
		if (argv[i] === '--input') input = argv[++i];
		else if (argv[i] === '--output') output = argv[++i];
	}
	return { input, output };
}

/** @param {string | undefined} input */
async function loadDb(input) {
	if (input) return JSON.parse(await readFile(input, 'utf8'));
	const res = await fetch(GEMOJI_DB_URL);
	if (!res.ok) throw new Error(`gemoji fetch failed: ${res.status} ${res.statusText}`);
	return res.json();
}

async function main() {
	const { input, output } = parseArgs(process.argv.slice(2));
	const db = await loadDb(input);
	const entries = emojiTableEntries(db);
	await writeFile(path.resolve(output), renderEmojiTable(entries), 'utf8');
	console.log(`wrote ${entries.length} shortcodes to ${output}`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
	main().catch((err) => {
		console.error(err);
		process.exit(1);
	});
}

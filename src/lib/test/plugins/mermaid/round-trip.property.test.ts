import { describe, it, expect, beforeAll } from 'vitest';
import fc from 'fast-check';
import { freshOrFixedSeed } from '#lib/test/invariants/arbitraries/property-seed.js';
import { parse, serialize } from '#lib';
import { grammar, type Block } from '#lib/plugin.js';
import { listGrammar } from '#lib/schema/own-syntax.js';
import { mermaid } from '#packages/mermaid/src/index.js';

// Awkward fence shapes for serialize(parse(src)) === src, read by an editor running mermaid and
// by one that doesn't, so uninstall safety comes out by construction. Pure byte identity, so even
// a code line that closes the fence early is a legal draw; that these shapes are reachable is
// pinned below.

const arbLineEnding = fc.constantFrom('\n', '\r\n');

const CODE_LINE_POOL = [
	'graph TD',
	'\tA[Start] --> B[End]',
	'A --> C',
	'',
	'  two leading spaces',
	'日本語ノード --> 中文',
	'label with 🎉 emoji',
	'~~~',
	'  ```'
];

const arbMermaidFence = fc
	.record({
		indent: fc.constantFrom('', ' ', '  ', '   '),
		char: fc.constantFrom('`', '~'),
		len: fc.integer({ min: 3, max: 5 }),
		infoRest: fc.constantFrom('', '   ', ' theme=dark', ' 日本語 flow'),
		openerEnding: arbLineEnding,
		codeLines: fc.array(fc.tuple(fc.constantFrom(...CODE_LINE_POOL), arbLineEnding), {
			maxLength: 5
		}),
		closer: fc.option(
			fc.record({
				indent: fc.constantFrom('', ' ', '   '),
				extraLen: fc.integer({ min: 0, max: 2 }),
				trail: fc.constantFrom('', ' ', '  '),
				ending: fc.constantFrom('\n', '\r\n', '')
			}),
			{ nil: undefined }
		),
		chopFinalNewline: fc.boolean()
	})
	.map(({ indent, char, len, infoRest, openerEnding, codeLines, closer, chopFinalNewline }) => {
		const opener = indent + char.repeat(len) + 'mermaid' + infoRest + openerEnding;
		const code = codeLines.map(([text, ending]) => text + ending).join('');
		const closerLine = closer
			? closer.indent + char.repeat(len + closer.extraLen) + closer.trail + closer.ending
			: '';
		const block = opener + code + closerLine;
		// An unclosed fence at EOF may also lack the final line ending.
		return !closer && chopFinalNewline ? block.replace(/(\r?\n)$/, '') : block;
	});

const arbDoc = fc
	.tuple(
		fc.constantFrom('', 'Above\n', 'Above\n\n', '# Heading\n\n'),
		arbMermaidFence,
		fc.constantFrom('', '\nAfter\n', '\n- a\n- b\n')
	)
	.map(([prefix, fence, suffix]) => prefix + fence + suffix);

const PARAMS = { numRuns: 300, seed: freshOrFixedSeed(20260710) } as const;

// fc.sample feeds the reachability self-tests, so its seed stays fixed: a fresh seed could miss
// a rare fence shape and flake.
let samples: string[] = [];
beforeAll(() => {
	samples = fc.sample(arbDoc, { numRuns: 800, seed: 20260710 });
});

const DIAGRAM = 'mermaid/diagram';

describe('mermaid round-trip property: plugin listed', () => {
	it('serialize(parse(s)) === s over generated fence shapes', () => {
		const { grammar: read } = listGrammar([mermaid], ({ cause }) => {
			throw cause;
		});
		fc.assert(
			fc.property(arbDoc, (src) => serialize(parse(src, { grammar: read as never })) === src),
			PARAMS
		);
	});

	// Evidence that the properties' own generator reaches the awkward fence shapes, read off the
	// diagrams an editor running mermaid reads.
	function sampledDiagrams(): Block[] {
		const read = grammar([mermaid]);
		return samples.flatMap((src) => read.parse(src).blocks.filter((b) => b.type.name === DIAGRAM));
	}
	/** Whether the diagram's last line closes its opener's run. */
	function closed(block: Block): boolean {
		const lines = block.text.replace(/\r?\n$/, '').split(/\r?\n/);
		const run = /^ {0,3}([`~]{3,})/.exec(lines[0])![1];
		const closer = new RegExp(`^ {0,3}${run[0]}{${run.length},}[ \\t]*$`);
		return lines.length > 1 && closer.test(lines[lines.length - 1]);
	}
	const reachable: Array<[label: string, probe: (block: Block) => boolean]> = [
		['CRLF line endings', (b) => b.text.includes('\r\n')],
		['~~~ fences', (b) => b.text.trimStart().startsWith('~')],
		['a missing closer at EOF', (b) => !closed(b)],
		['an indented opener', (b) => b.text.startsWith(' ')],
		['unicode in the code body', (b) => b.body.includes('日本語ノード')]
	];
	for (const [label, probe] of reachable) {
		it(`can generate ${label}`, () => {
			expect(sampledDiagrams().some(probe)).toBe(true);
		});
	}
});

describe('mermaid round-trip property: plugin not listed', () => {
	it('the same generated bytes read as GFM and round-trip', () => {
		fc.assert(
			fc.property(arbDoc, (src) => {
				const doc = parse(src);
				if (
					grammar([])
						.parse(src)
						.blocks.some((b) => b.type.name === DIAGRAM)
				)
					return false;
				return serialize(doc) === src;
			}),
			PARAMS
		);
	});
});

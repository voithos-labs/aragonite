// Writes `src/renderer/catalog.ts` from highlight.js's own grammar files: each grammar's name, the other
// spellings it declares, and a loader, left null for the grammars `src/renderer/eager.ts` imports.
// Formatted as the repo formats it; `node scripts/catalog.mjs --check` exits 1 when the file on disk
// has drifted.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(path.join(root, 'package.json'));
const grammars = path.join(
	path.dirname(require.resolve('highlight.js/package.json')),
	'lib/languages'
);
const hljs = require('highlight.js/lib/core');

const eager = new Set(
	[
		...readFileSync(path.join(root, 'src/renderer/eager.ts'), 'utf8').matchAll(
			/languages\/([\w-]+)'/g
		)
	].map(([, name]) => name)
);
const names = readdirSync(grammars)
	.filter((file) => file.endsWith('.js') && !file.endsWith('.js.js'))
	.map((file) => file.slice(0, -3))
	.sort();

const key = (name) => (/^[a-z_$][\w$]*$/.test(name) ? name : `'${name}'`);
const rows = names.map((name) => {
	const aliases = (require(path.join(grammars, `${name}.js`))(hljs).aliases ?? []).join(' ');
	const load = eager.has(name) ? 'null' : `() => import('highlight.js/lib/languages/${name}')`;
	return `\t${key(name)}: ['${aliases}', ${load}]`;
});

const source = `// Generated by \`npm run catalog\` from highlight.js's grammar files; a test fails when it drifts.
import type { LanguageFn } from 'highlight.js';

type Load = () => Promise<{ default: LanguageFn }>;

/** Every highlight.js grammar by name: its other spellings, space-separated, and its loader (null
 *  for one the package loads eagerly). */
export const CATALOG: Readonly<Record<string, readonly [string, Load | null]>> = {
${rows.join(',\n')}
};
`;

const file = path.join(root, 'src/renderer/catalog.ts');
const prettier = await import('prettier');
const text = await prettier.format(source, {
	...(await prettier.resolveConfig(file)),
	filepath: file
});
if (process.argv.includes('--check')) {
	if (readFileSync(file, 'utf8') !== text) {
		console.error('src/renderer/catalog.ts has drifted from highlight.js; run `npm run catalog`');
		process.exit(1);
	}
} else writeFileSync(file, text);
